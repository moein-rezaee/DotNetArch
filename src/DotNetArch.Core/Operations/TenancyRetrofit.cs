using System.Text;
using System.Text.RegularExpressions;
using DotNetArch.Core.Config;
using DotNetArch.Core.NetArch;
using DotNetArch.Core.Scaffolding.V2;

namespace DotNetArch.Core.Operations;

internal sealed record TenantEntity(string Name, string File, bool Scoped);

internal sealed record TenantDbContext(string File, string Name, IReadOnlyList<TenantEntity> Entities);

/// <summary>Finds the EF context of a service and the entities it persists, and whether each already belongs to a tenant.</summary>
internal static class TenancyModel
{
    internal const string Marker = "ITenantOwned";
    private static readonly TimeSpan Timeout = TimeSpan.FromSeconds(1);

    public static TenantDbContext? Find(string root, out string? problem)
    {
        problem = null;
        var src = Path.Combine(root, "src");
        if (!Directory.Exists(src))
        {
            problem = "There is no src/ folder.";
            return null;
        }

        var files = Directory.EnumerateFiles(src, "*.cs", SearchOption.AllDirectories).Where(f => !IsSkipped(f)).ToList();
        var contexts = files.Select(f => (File: f, Match: Regex.Match(System.IO.File.ReadAllText(f), @"class\s+(?<name>\w+)\s*:\s*DbContext\b", RegexOptions.CultureInvariant, Timeout)))
            .Where(c => c.Match.Success)
            .ToList();
        if (contexts.Count != 1)
        {
            problem = contexts.Count == 0 ? "No class derived from DbContext was found." : "More than one DbContext was found: " + string.Join(", ", contexts.Select(c => c.Match.Groups["name"].Value));
            return null;
        }

        var contextText = System.IO.File.ReadAllText(contexts[0].File);
        var entities = new List<TenantEntity>();
        foreach (Match set in Regex.Matches(contextText, @"DbSet<(?<type>\w+)>\s+\w+", RegexOptions.CultureInvariant, Timeout))
        {
            var type = set.Groups["type"].Value;
            var declaration = new Regex($@"\bclass\s+{Regex.Escape(type)}\b", RegexOptions.CultureInvariant, Timeout);
            var file = files.FirstOrDefault(f => declaration.IsMatch(System.IO.File.ReadAllText(f)));
            if (file is not null)
                entities.Add(new TenantEntity(type, file, System.IO.File.ReadAllText(file).Contains(Marker, StringComparison.Ordinal)));
        }

        return new TenantDbContext(contexts[0].File, contexts[0].Match.Groups["name"].Value, entities);
    }

    private static bool IsSkipped(string path)
    {
        var separator = Path.DirectorySeparatorChar;
        return path.Contains($"{separator}obj{separator}", StringComparison.Ordinal)
               || path.Contains($"{separator}bin{separator}", StringComparison.Ordinal)
               || path.Contains($"{separator}Migrations{separator}", StringComparison.Ordinal);
    }
}

/// <summary>
/// <c>add_tenancy</c>: makes a service that was not generated by the tool multi-tenant (tenant = Keycloak realm), mechanically and repeatably. The
/// tenancy Kit comes from a shared profile (the tool names no kit): its packages and host lines are wired, every entity the EF context persists gets a
/// <c>TenantId</c>, the context filters every query by the tenant of the caller and stamps the tenant on every new row. An operator (and a context with
/// no caller, such as a migration) sees every tenant. What cannot be done safely by text (a context with its own SaveChanges override, an entity
/// that is a record) is listed as manual.
/// </summary>
internal static class TenancyRetrofit
{
    private static readonly TimeSpan Timeout = TimeSpan.FromSeconds(1);

    public static readonly OperationDefinition Definition = new(
        "add_tenancy",
        "Make an existing service multi-tenant: wire the tenancy kit of a shared profile, give every persisted entity a TenantId, filter every query by the caller's tenant and stamp the tenant on new rows (operators see all tenants). Safe to repeat. Add the EF migration afterwards. Plan first; writes only with apply.",
        OperationKind.Mutating,
        new[]
        {
            new OperationParameter("path", "Repository root of the service.", Required: true, Positional: true, Alias: "output", Default: "@saved"),
            new OperationParameter("profile", "Shared profile file that lists the tenancy kit (its packages and host lines).", Required: true),
            new OperationParameter("skip", "Comma-separated entity names that stay shared across tenants (for example a catalogue of providers)."),
        },
        Run);

    private static OperationResult Run(OperationRequest request)
    {
        var path = Path.GetFullPath(request.Get("path") ?? throw new ArgumentException("Missing required value 'path'."));
        if (!Directory.Exists(path))
            throw new ArgumentException($"Folder not found: {path}");

        var profilePath = Path.GetFullPath(request.Get("profile") ?? throw new ArgumentException("Missing required value 'profile'."));
        var profile = File.Exists(profilePath) ? NetArchStore.LoadProfileFile(profilePath) : null;
        var tenancy = profile?.ExternalKits.FirstOrDefault(kit => kit.Area.Equals("Tenancy", StringComparison.OrdinalIgnoreCase))
            ?? throw new ArgumentException($"The profile '{request.Get("profile")}' lists no kit with the area 'Tenancy'.");
        var skip = (request.Get("skip") ?? string.Empty).Split(',', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries).ToHashSet(StringComparer.Ordinal);

        return ScaffoldRunner.Run(request, "add_tenancy", path, skipMigrations: true, work =>
        {
            var config = ConfigManager.Load(work) ?? ConfigDeriver.Derive(work)
                ?? throw new InvalidOperationException("The folder is not a layout v2/v3 solution with an Api project.");
            config.SolutionPath = work;
            var manual = new List<string>();
            Apply(work, config, tenancy, skip, manual);
            foreach (var note in manual)
                DotNetArch.Core.Hosting.ToolHost.Info("manual: " + note);
        }, normalize: false);
    }

    private static void Apply(string work, SolutionConfig config, ExternalKit tenancy, HashSet<string> skip, List<string> manual)
    {
        var model = TenancyModel.Find(work, out var problem) ?? throw new InvalidOperationException(problem);
        var domain = Path.Combine(work, "src", $"{config.SolutionName}.Domain");
        if (!Directory.Exists(domain))
            throw new InvalidOperationException($"The Domain project src/{config.SolutionName}.Domain was not found.");

        var wiring = new ProfileDefinition { Name = "tenancy", ExternalKits = { tenancy } };
        ExternalKitWiring.Apply(config, wiring);
        var contextProject = ProjectFileOf(Path.GetDirectoryName(model.File)!);
        foreach (var package in tenancy.Packages.Where(p => p.Id.EndsWith(".Abstractions", StringComparison.Ordinal)))
            ExternalKitWiring.EnsurePackage(config, contextProject, package.Id, package.Version);

        var domainNamespace = $"{config.SolutionName}.Domain.Tenancy";
        Directory.CreateDirectory(Path.Combine(domain, "Tenancy"));
        File.WriteAllText(Path.Combine(domain, "Tenancy", "ITenantOwned.cs"), InterfaceSource(domainNamespace), new UTF8Encoding(false));

        var scoped = new List<string>();
        foreach (var entity in model.Entities.Where(e => !skip.Contains(e.Name)))
        {
            if (!entity.Scoped && !PatchEntity(entity, domainNamespace, manual))
                continue;
            scoped.Add(entity.Name);
        }

        PatchContext(model, scoped, domainNamespace, manual);
    }

    private static string ProjectFileOf(string directory)
    {
        for (var current = directory; current.Length > 1; current = Path.GetDirectoryName(current)!)
        {
            var project = Directory.EnumerateFiles(current, "*.csproj").FirstOrDefault();
            if (project is not null)
                return project;
        }

        throw new InvalidOperationException("The project of the DbContext was not found.");
    }

    private static string InterfaceSource(string ns) => $$"""
        namespace {{ns}};

        /// <summary>An entity that belongs to one tenant (a Keycloak realm). The EF context filters by it and stamps it on new rows.</summary>
        public interface ITenantOwned
        {
            string TenantId { get; set; }
        }

        """;

    private static bool PatchEntity(TenantEntity entity, string domainNamespace, List<string> manual)
    {
        var text = File.ReadAllText(entity.File);
        var declaration = new Regex($@"(?<head>\bclass\s+{Regex.Escape(entity.Name)})(?<bases>[ \t]*:[ \t]*[^\r\n{{]+?)?(?<tail>[ \t]*\r?\n?[ \t]*\{{)", RegexOptions.CultureInvariant, Timeout);
        var match = declaration.Match(text);
        if (!match.Success)
        {
            manual.Add($"{entity.Name}: the class declaration was not recognised ({Path.GetFileName(entity.File)}); add ITenantOwned and a TenantId property by hand");
            return false;
        }

        var bases = match.Groups["bases"].Success ? match.Groups["bases"].Value.TrimEnd() + ", " + TenancyModel.Marker : " : " + TenancyModel.Marker;
        var newline = text.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        var property = $"{newline}    public string TenantId {{ get; set; }} = string.Empty;{newline}";
        text = text.Remove(match.Index, match.Length).Insert(match.Index, match.Groups["head"].Value + bases + match.Groups["tail"].Value + property);
        File.WriteAllText(entity.File, AddUsing(text, domainNamespace), new UTF8Encoding(false));
        return true;
    }

    private static void PatchContext(TenantDbContext model, List<string> scoped, string domainNamespace, List<string> manual)
    {
        var text = File.ReadAllText(model.File);
        if (text.Contains("ApplyTenancy(", StringComparison.Ordinal))
            return;

        var name = model.Name;
        var constructor = new Regex($@"public\s+{name}\s*\(\s*DbContextOptions<{name}>\s+(?<o>\w+)\s*\)\s*:\s*base\(\k<o>\)\s*\{{\s*\}}", RegexOptions.CultureInvariant, Timeout).Match(text);
        var onModelCreating = new Regex(@"protected\s+override\s+void\s+OnModelCreating\(\s*ModelBuilder\s+(?<m>\w+)\s*\)\s*\{", RegexOptions.CultureInvariant, Timeout).Match(text);
        if (!constructor.Success || !onModelCreating.Success || Regex.IsMatch(text, @"override\s+(int\s+SaveChanges|Task<int>\s+SaveChangesAsync)", RegexOptions.CultureInvariant, Timeout))
        {
            manual.Add($"{name}: the context has a shape the tool does not patch (a constructor other than (DbContextOptions<{name}> options), no OnModelCreating, or its own SaveChanges override); apply the tenant filter and stamp by hand");
            return;
        }

        var nl = text.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        var options = constructor.Groups["o"].Value;
        var builder = onModelCreating.Groups["m"].Value;
        var members = new StringBuilder();
        members.Append($"public {name}(DbContextOptions<{name}> {options}, ICallerContext? caller = null)").Append(nl)
            .Append($"        : base({options})").Append(nl)
            .Append("    {").Append(nl)
            .Append("        _caller = caller;").Append(nl)
            .Append("    }").Append(nl).Append(nl)
            .Append("    private const string NoTenant = \"(none)\";").Append(nl)
            .Append("    private readonly ICallerContext? _caller;").Append(nl).Append(nl)
            .Append("    // An operator, and a context with no caller (a migration), sees every tenant; anyone else sees only the tenant of the token.").Append(nl)
            .Append("    private string? CurrentTenantId => _caller is null || _caller.IsOperator ? null : _caller.TenantId ?? NoTenant;").Append(nl).Append(nl)
            .Append("    public override int SaveChanges(bool acceptAllChangesOnSuccess)").Append(nl)
            .Append("    {").Append(nl)
            .Append("        StampTenant();").Append(nl)
            .Append("        return base.SaveChanges(acceptAllChangesOnSuccess);").Append(nl)
            .Append("    }").Append(nl).Append(nl)
            .Append("    public override System.Threading.Tasks.Task<int> SaveChangesAsync(bool acceptAllChangesOnSuccess, System.Threading.CancellationToken cancellationToken = default)").Append(nl)
            .Append("    {").Append(nl)
            .Append("        StampTenant();").Append(nl)
            .Append("        return base.SaveChangesAsync(acceptAllChangesOnSuccess, cancellationToken);").Append(nl)
            .Append("    }").Append(nl).Append(nl)
            .Append("    // A new row belongs to the tenant of the caller unless it already names one; no tenant and no name is refused.").Append(nl)
            .Append("    private void StampTenant()").Append(nl)
            .Append("    {").Append(nl)
            .Append($"        foreach (var entry in ChangeTracker.Entries<{TenancyModel.Marker}>())").Append(nl)
            .Append("        {").Append(nl)
            .Append("            if (entry.State != EntityState.Added || !string.IsNullOrEmpty(entry.Entity.TenantId))").Append(nl)
            .Append("                continue;").Append(nl).Append(nl)
            .Append("            entry.Entity.TenantId = _caller?.TenantId ?? throw new TenantRequiredException();").Append(nl)
            .Append("        }").Append(nl)
            .Append("    }").Append(nl).Append(nl)
            .Append($"    private void ApplyTenancy(ModelBuilder {builder})").Append(nl)
            .Append("    {").Append(nl);
        foreach (var entity in scoped)
        {
            members.Append($"        {builder}.Entity<{entity}>(entity =>").Append(nl)
                .Append("        {").Append(nl)
                .Append("            entity.Property(e => e.TenantId).IsRequired().HasMaxLength(64);").Append(nl)
                .Append("            entity.HasIndex(e => e.TenantId);").Append(nl)
                .Append("            entity.HasQueryFilter(e => CurrentTenantId == null || e.TenantId == CurrentTenantId);").Append(nl)
                .Append("        });").Append(nl);
        }

        members.Append("    }");
        text = text.Remove(constructor.Index, constructor.Length).Insert(constructor.Index, members.ToString());
        var call = new Regex($@"(?<indent>[ \t]*)base\.OnModelCreating\({builder}\);", RegexOptions.CultureInvariant, Timeout).Match(text);
        text = call.Success
            ? text.Insert(call.Index, $"{call.Groups["indent"].Value}ApplyTenancy({builder});{nl}")
            : Regex.Replace(text, @"(protected\s+override\s+void\s+OnModelCreating\([^)]*\)\s*\{)", $"$1{nl}        ApplyTenancy({builder});", RegexOptions.CultureInvariant, Timeout);
        text = AddUsing(AddUsing(text, "Corevia.Kit.Tenancy"), domainNamespace);
        File.WriteAllText(model.File, text, new UTF8Encoding(false));
    }

    private static string AddUsing(string text, string ns)
    {
        var line = $"using {ns};";
        if (text.Contains(line, StringComparison.Ordinal))
            return text;

        var nl = text.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        var last = Regex.Matches(text, @"^using [^\r\n]+;", RegexOptions.Multiline | RegexOptions.CultureInvariant, Timeout).LastOrDefault();
        return last is null ? line + nl + text : text.Insert(last.Index + last.Length, nl + line);
    }
}
